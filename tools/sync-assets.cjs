#!/usr/bin/env node
// Generate the offline manifest and a shared content version for shell and lazy modules.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const context = vm.createContext({ self: {} });
vm.runInContext(read('js/game-catalog.js'), context);
const catalog = context.self.GameCatalog;
catalog.validate(catalog.list);
const originalHTML = read('index.html');
const marker = /  <!-- games:start[^\n]*-->[\s\S]*?  <!-- games:end -->/;
if (!marker.test(originalHTML)) throw new Error('Missing game script markers in index.html');
const html = originalHTML.replace(marker, '  <!-- games:start (modules loaded on demand from GameCatalog) -->\n  <!-- games:end -->');
const paths = [...html.matchAll(/(?:src|href)="([^"#]+)"/g)].map(match => match[1]);
const icons = fs.readdirSync(path.join(root, 'icons')).filter(file => file.endsWith('.png')).sort().map(file => 'icons/' + file);
const gameFiles = catalog.list.flatMap(game => [...game.scripts, game.file, ...game.assets]);
const assets = [...new Set(['./', './index.html', ...paths.concat(icons, gameFiles).map(file => './' + file)])];
for (const asset of assets) {
  if (asset !== './' && asset !== './js/release.js' && !fs.statSync(path.join(root, asset)).isFile()) throw new Error('Missing offline asset: ' + asset);
}
const listed = new Set(catalog.list.map(game => path.basename(game.file)));
for (const file of fs.readdirSync(path.join(root, 'js/games')).filter(file => file.endsWith('.js'))) {
  if (!listed.has(file)) throw new Error('Game file is absent from catalog: ' + file);
}
const originalSW = read('sw.js');
const hash = crypto.createHash('sha256');
for (const asset of assets.filter(asset => asset !== './' && asset !== './js/release.js').sort()) {
  hash.update(asset + '\0');
  hash.update(asset === './index.html' ? html : fs.readFileSync(path.join(root, asset)));
}
hash.update(originalSW.replace(/const ASSETS = \[[\s\S]*?\];/, '').replace(/const BUILD = '[^']*';/, ''));
const build = hash.digest('hex').slice(0, 16);
const release = '/* Generated by tools/sync-assets.cjs. */\n(function (global) { global.AppBuild = { id: ' + JSON.stringify(build) + ' }; })(window);\n';
const assetBlock = 'const ASSETS = ' + JSON.stringify(assets, null, 2).replace(/"/g, "'") + ';';
if (!/const ASSETS = \[[\s\S]*?\];/.test(originalSW) || !/const BUILD = '[^']*';/.test(originalSW)) throw new Error('Missing manifest markers in sw.js');
const sw = originalSW.replace(/const ASSETS = \[[\s\S]*?\];/, assetBlock).replace(/const BUILD = '[^']*';/, "const BUILD = '" + build + "';");
let stale = false;
for (const [file, before, after] of [['index.html', originalHTML, html], ['sw.js', originalSW, sw], ['js/release.js', fs.existsSync(path.join(root, 'js/release.js')) ? read('js/release.js') : '', release]]) {
  if (before === after) continue;
  if (process.argv.includes('--check')) { console.error('Outdated generated assets: ' + file); stale = true; }
  else { fs.writeFileSync(path.join(root, file), after); console.log('Updated ' + file); }
}
if (stale) process.exitCode = 1;
else console.log('Catalog and offline assets agree (' + catalog.list.length + ' games, build ' + build + ').');
